-- Initial scheme

CREATE TABLE SETTINGS (
    name  TEXT NOT NULL PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE BODY_METRIC (
    date        INTEGER NOT NULL PRIMARY KEY,
    weight      REAL NOT NULL,
    fat_ratio   REAL NOT NULL,
    lean_mass   REAL NOT NULL,
    water_ratio REAL NOT NULL
);
CREATE INDEX BODY_METRIC_DATE ON BODY_METRIC(date);

CREATE TABLE DEVICE (
    serial     TEXT NOT NULL PRIMARY KEY,
    model      TEXT NOT NULL,
    last_sync  INTEGER
);

CREATE TABLE WORKOUT (
    name TEXT NOT NULL PRIMARY KEY
);

CREATE TABLE SPORT (
    id INTEGER NOT NULL PRIMARY KEY
);

CREATE TABLE SUB_SPORT (
    sport INTEGER NOT NULL REFERENCES SPORT(id),
    id INTEGER NOT NULL,
    PRIMARY KEY (sport, id),
    FOREIGN KEY (sport) REFERENCES SPORT(id) ON DELETE CASCADE
);
CREATE INDEX SUB_SPORT_SPORT ON SUB_SPORT(sport);

CREATE TABLE SESSION (
    date                INTEGER NOT NULL PRIMARY KEY,
    name                TEXT NOT NULL,
    total_elapsed_time  INTEGER NOT NULL,
    active_time         INTEGER NOT NULL DEFAULT 0,
    total_calories      INTEGER NOT NULL,
    metabolic_calories  INTEGER NOT NULL,
    training_load       INTEGER NOT NULL DEFAULT 0,
    workout             TEXT,
    sport               INTEGER,
    sub_sport           INTEGER,
    device              TEXT DEFAULT NULL,
    FOREIGN KEY (sport, sub_sport) REFERENCES SUB_SPORT(sport, id) ON DELETE CASCADE
);
CREATE INDEX SESSION_NAME ON SESSION(name);

CREATE TABLE EXERCISE_CATEGORY (
    id INTEGER NOT NULL PRIMARY KEY
);

CREATE TABLE EXERCISE (
    category INTEGER NOT NULL REFERENCES EXERCISE_CATEGORY(id),
    id       INTEGER NOT NULL,
    PRIMARY KEY (category, id),
    FOREIGN KEY (category) REFERENCES EXERCISE_CATEGORY(id) ON DELETE CASCADE
);
CREATE INDEX EXERCISE_EXERCISE_CATEGORY ON EXERCISE(category);

CREATE TABLE SERIE (
    session           INTEGER NOT NULL,
    idx               INTEGER NOT NULL,
    exercise_category INTEGER NOT NULL,
    exercise_id       INTEGER NOT NULL,
    reps              INTEGER NOT NULL,
    weight            REAL NOT NULL,
    pr                BOOLEAN NOT NULL,
    PRIMARY KEY (session, idx),
    FOREIGN KEY (session) REFERENCES SESSION(date) ON DELETE CASCADE,
    FOREIGN KEY (exercise_category, exercise_id) REFERENCES EXERCISE(category, id) ON DELETE CASCADE
);
CREATE INDEX SERIE_EXERCISE     ON SERIE(exercise_category, exercise_id);
CREATE INDEX SERIE_SESSION      ON SERIE(session);
CREATE INDEX SERIE_PR           ON SERIE(pr);
CREATE UNIQUE INDEX SERIE_EXERCISE_PR  ON SERIE(exercise_category, exercise_id) WHERE pr = 1;

CREATE TABLE ADDITIONAL_DATA (
    session      INTEGER NOT NULL PRIMARY KEY,
    heart_rates  BLOB DEFAULT NULL,
    coordinates  BLOB DEFAULT NULL,
    speeds       BLOB DEFAULT NULL,
    cadences     BLOB DEFAULT NULL,
    powers       BLOB DEFAULT NULL,
    respirations BLOB DEFAULT NULL,
    FOREIGN KEY (session) REFERENCES SESSION(date) ON DELETE CASCADE
);

